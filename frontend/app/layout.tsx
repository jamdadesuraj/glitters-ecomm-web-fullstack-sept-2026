import type { Metadata } from "next";
import { Jura } from "next/font/google";

import "./globals.css";
import LayoutShell from "./components/LayoutShell";
import { ReduxProviders } from "@/providers/ReduxProviders";
import { ToastContainer } from "react-toastify";
import "react-toastify/dist/ReactToastify.css";

const jura = Jura({
  weight: ["300", "400", "500", "600", "700"],
  variable: "--font-jura",
});

// change this to your real site name
const SITE_TITLE = "Glitters Mobile";

export async function generateMetadata(): Promise<Metadata> {
  let favicon = "/favicon.ico";

  try {
    const res = await fetch(`${process.env.NEXT_PUBLIC_API_URL}/settings`, {
      next: { revalidate: 60 },
    });
    const json = await res.json();
    const url = json?.data?.[0]?.favicon;
    if (url) favicon = url;
  } catch {
    // backend unreachable: keep the default favicon
  }

  return {
    title: {
      default: SITE_TITLE,
      template: `%s | ${SITE_TITLE}`,
    },
    description: "Generated by create next app",
    icons: {
      icon: favicon,
      shortcut: favicon,
      apple: favicon,
    },
  };
}

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en" className={`${jura.className} bg-white`}>
      <body className="flex min-h-screen flex-col bg-white">
        <ReduxProviders>
          <LayoutShell>{children}</LayoutShell>

          <ToastContainer
            position="top-right"
            autoClose={3000}
            hideProgressBar={false}
            newestOnTop
            closeOnClick
            pauseOnHover
            draggable
            theme="light"
          />
        </ReduxProviders>
      </body>
    </html>
  );
}
