import mongoose, { Schema } from "mongoose";
import { IBlogCategory } from "./blogsCategory.interface";

const blogsCategorySchema: Schema = new Schema(
  {
    categoryName: {
      type: String,
      required: true,
      trim: true,
    },
    status: {
      type: String,
      enum: ["active", "inactive"],
      default: "active",
      trim: true,
    },
  },
  {
    timestamps: true,
    toJSON: {
      transform: function (doc, ret: any) {
        ret.createdAt = new Date(ret.createdAt).toLocaleString("en-IN", {
          timeZone: "Asia/Kolkata",
        });

        ret.updatedAt = new Date(ret.updatedAt).toLocaleString("en-IN", {
          timeZone: "Asia/Kolkata",
        });

        return ret;
      },
    },
  },
);

export const BlogsCategoryModel = mongoose.model<IBlogCategory>(
  "BlogsCategoryModel",
  blogsCategorySchema,
);
